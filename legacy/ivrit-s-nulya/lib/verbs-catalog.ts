function lamedHe(
  inf: string,
  pres: [string, string, string, string],
  past: Record<'1sg' | '3ms' | '3fs' | '3pl', string>,
  fut: Record<'1sg' | '2ms' | '2fs' | '3ms' | '3pl', string>,
  imp: [string, string, string]
): Partial<Conjugation> {
  return {
    infinitive: inf,
    present: { ms: pres[0], fs: pres[1], mp: pres[2], fp: pres[3] },
    past: {
      '1sg': past['1sg'],
      '2ms': past['1sg'].replace(/תִּי$/, 'תָּ'),
      '2fs': past['1sg'].replace(/תִּי$/, 'ת'),
      '3ms': past['3ms'],
      '3fs': past['3fs'],
      '1pl': past['1sg'].replace(/תִּי$/, 'נוּ'),
      '2mp': past['1sg'].replace(/^./, (ch) => ch).replace(/תִּי$/, 'תֶּם'),
      '2fp': past['1sg'].replace(/תִּי$/, 'תֶּן'),
      '3pl': past['3pl'],
    },
    future: {
      '1sg': fut['1sg'],
      '2ms': fut['2ms'],
      '2fs': fut['2fs'],
      '3ms': fut['3ms'],
      '3fs': fut['2ms'],
      '1pl': fut['1sg'].replace(/^א/, 'נ'),
      '2mp': fut['3pl'].replace(/^י/, 'ת'),
      '2fp': `${fut['2ms']}נָה`,
      '3pl': fut['3pl'],
    },
    imperative: { ms: imp[0], fs: imp[1], mp: imp[2], fp: `${imp[0]}נָה` },
  };
}

