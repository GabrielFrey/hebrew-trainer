import type { Conjugation, VerbBuild, VerbPattern, BinyanId } from '@/lib/verbs-engine';
import type { LevelId } from '@/lib/types';

export type VerbEntry = VerbBuild & {
  id: string;
  ru: string;
  en: string;
  level: LevelId;
};

function v(
  id: string,
  root: string,
  binyan: BinyanId,
  ru: string,
  en: string,
  level: LevelId,
  pattern: VerbPattern = 'strong',
  extra?: Partial<Pick<VerbEntry, 'sin' | 'forms'>>
): VerbEntry {
  return { id, root, binyan, ru, en, level, pattern, ...extra };
}

function special(
  id: string,
  root: string,
  binyan: BinyanId,
  ru: string,
  en: string,
  level: LevelId,
  forms: Partial<Conjugation>
): VerbEntry {
  return { id, root, binyan, ru, en, level, pattern: 'special', forms };
}

